#!/usr/bin/env python3
"""Generate the stubs page from stub_census.py.

The page lists every empty or near-empty `UFUNCTION` body in Script/, one row each, grouped by
file. It is generated: a hand edit is overwritten on the next run.

    python gen_stubs_doc.py            # write the page
    python gen_stubs_doc.py --check    # exit 1 when the page on disk is stale

A row carries what the census can read from the file: the declaration line, the class and the
function, the return type, the anchored form the census matched, the specifiers, and the first
sentence of the doc comment above the declaration. Whether a stub is finished by design or
unfinished is not decided here; the comment above the declaration is where that is written.

Project settings (`.octopus/ue-angelscript.json`, object `gen_stubs_doc`): `output`, the page path
relative to the project root, and the three commands the page names.
"""
import collections
import io
import os
import re
import subprocess
import sys
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "unreal" / "tools"))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import _project  # noqa: E402

ROOT = str(_project.project_root())
CFG = _project.config("ue-angelscript").get("gen_stubs_doc", {})
os.chdir(ROOT)
OUT = os.path.join(*CFG.get("output", "Docs/STUBS.md").split("/"))
CHECK = "--check" in sys.argv
HERE = os.path.dirname(os.path.abspath(__file__))
GENERATOR = CFG.get("generatorCommand", "python gen_stubs_doc.py")
CENSUS = CFG.get("censusCommand", "stub_census.py")
OVERRIDES = CFG.get("overrideCensusCommand", "python collision_census.py --all")


def census():
    """Head figures from stdout; rows from the JSON dump, which carries the isreal flag the TSV lacks."""
    import json
    import tempfile
    tmp = os.path.join(tempfile.gettempdir(), "stub_census.json")
    res = subprocess.run([sys.executable, os.path.join(HERE, "stub_census.py"), "--project", ROOT,
                          "--json", tmp],
                         capture_output=True, text=True, timeout=600, encoding="utf-8",
                         errors="replace")
    head = {}
    for line in res.stdout.splitlines():
        m = re.match(r"^(total anchored UFUNCTION declarations|empty / near-empty bodies|"
                     r"\s*of which REAL one-line bodies|TRUE stubs|files with at least one true stub):\s+(\d+)", line)
        if m:
            head[m.group(1).strip()] = int(m.group(2))
    with open(tmp, encoding="utf-8") as fh:
        recs = json.load(fh)
    rows = []
    for r in sorted(recs, key=lambda x: (x["file"], x["line"])):
        if r.get("isreal"):
            continue
        rows.append([str(r.get(h, "")) for h in ("file", "line", "class", "name", "ret", "why",
                                                  "spec", "comment", "body")])
    return head, rows


def first_sentence(comment):
    c = comment.strip()
    c = re.sub(r"^/\*\*\s*|\s*\*/$", "", c)
    c = re.sub(r"\s*\*\s+", " ", c)
    c = re.sub(r"//\s*DOC:.*$", "", c).strip()
    c = re.sub(r"\s+", " ", c)
    m = re.match(r"(.+?\.)(\s|$)", c)
    return (m.group(1) if m else c)[:140]


def render(head, rows):
    out = io.StringIO()
    p = lambda s="": out.write(s + "\n")
    p("# Empty bodies in `Script/`")
    p()
    p("Generated by `%s` from `%s` on %s. Do not edit; rerun."
      % (GENERATOR, CENSUS, date.today().isoformat()))
    p()
    p("| Figure | Value |")
    p("|---|---:|")
    p("| anchored `UFUNCTION` declarations | %d |" % head.get("total anchored UFUNCTION declarations", 0))
    p("| empty or near-empty bodies | %d |" % head.get("empty / near-empty bodies", 0))
    p("| of which a real one-line member write | %d |" % head.get("of which REAL one-line bodies", 0))
    p("| **true stubs** | **%d** |" % head.get("TRUE stubs", 0))
    p("| files with at least one | %d |" % head.get("files with at least one true stub", 0))
    p()
    p("`why` is the anchored form the census matched: `empty`, `constant return` or `constant assignment`.")
    p("A `BlueprintEvent` stub with no override in any Blueprint and no `BlueprintOverride` in any `.as`")
    p("subclass answers that constant for the whole run; the override census is")
    p("`%s`, section `NOT WORK`." % OVERRIDES)
    p()
    by_file = collections.OrderedDict()
    for c in rows:
        by_file.setdefault(c[0].replace("\\", "/"), []).append(c)
    for f, rs in by_file.items():
        p("## `%s` — %d" % (f, len(rs)))
        p()
        p("| Line | Function | Returns | Why | Specifiers | Body | Comment |")
        p("|---:|---|---|---|---|---|---|")
        for c in rs:
            body = c[8].replace("|", "\\|").strip()
            p("| %s | `%s::%s` | `%s` | %s | `%s` | `%s` | %s |" % (
                c[1], c[2], c[3], c[4], c[5], c[6], body, first_sentence(c[7]).replace("|", "\\|")))
        p()
    return out.getvalue()


def main():
    head, rows = census()
    text = render(head, rows)
    norm = lambda s: re.sub(r"on \d{4}-\d{2}-\d{2}\.", "on DATE.", s)
    if CHECK:
        try:
            cur = open(OUT, encoding="utf-8").read()
        except FileNotFoundError:
            cur = ""
        if norm(cur) != norm(text):
            print("STALE: %s - run %s" % (OUT, GENERATOR))
            return 1
        print("current: %s" % OUT)
        return 0
    os.makedirs(os.path.dirname(OUT) or ".", exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("wrote %s: %d stubs in %d files" % (OUT, len(rows), len({c[0] for c in rows})))
    return 0


if __name__ == "__main__":
    sys.exit(main())
